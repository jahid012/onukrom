    fun error(code: String?, fallback: String?): String = errors[code] ?: fallback ?: serverProblem

    fun ago(millis: Long?): String {
        if (millis == null || millis <= 0) return never
        val min = ((System.currentTimeMillis() - millis) / 60000).toInt()
        return when {
            min < 1 -> justNow
            min < 60 -> minutesAgo(min)
            min < 60 * 24 -> hoursAgo(min / 60)
            else -> daysAgo(min / (60 * 24))
        }
    }
}

